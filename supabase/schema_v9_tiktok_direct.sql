-- ============================================================================
-- 投稿卓 NEO / v9 … TikTok に直接投稿するための「投稿ごとの設定」
--
-- ★ 何が変わるか
--   いままで TikTok は下書き送信だけだった。本文を一緒に送れず、
--   公開は本人が TikTok アプリで手で押していた。
--   直接投稿（video.publish）では、本文・公開範囲・コメント可否などを
--   一緒に送り、そのまま公開される。
--
-- ★ なぜ投稿ごとに持つのか
--   TikTok の決まりで、公開範囲は本人が投稿のたびに選ぶ（既定値を置かない）。
--   コメント／デュエット／スティッチの可否、商用コンテンツの申告、
--   規約への同意も、投稿ごとに本人が決めたものを送る。
--   運用アカウントの設定として1つに決めてしまうことはできない。
--
-- ★ 中身は jsonb。形は lib/tiktok-settings.js の normalize() が決める。
--   空（null）の投稿は、いままでどおり下書き送信になる。
--   だからこの移行だけで、動いている予約投稿の動きは変わらない。
--
-- ★ 何度流しても壊れません。
-- ============================================================================

alter table posts add column if not exists tt_settings jsonb;

comment on column posts.tt_settings is
  'TikTok 直接投稿の設定（公開範囲・コメント等の可否・商用申告・同意）。null なら下書き送信。';
