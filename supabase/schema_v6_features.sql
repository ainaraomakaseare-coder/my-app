-- 投稿卓 NEO — 運用アカウントごとに「使う機能」を決める
--
--   ジャンルによって、要る道具が違う。
--
--     転職アフィリエイト … 文案も動画も自動で作る
--     ひろや｜AI初心者   … いまは自分で書く。動画も作らない
--
--   全部のチャンネルに同じ機能を並べると、使わない画面が邪魔になる。
--   かといって消してしまうと、あとで使いたくなったときに戻せない。
--   だから「切り替え」にする。
--
--   ★ 増やすのは2つだけにした。
--     writes … 文案を自動で書く
--     videos … 動画を自動で作る
--     この2つが独立していれば、必要な組み合わせは全部言える。
--       転職        … {writes, videos}
--       AI初心者(今) … {}
--       AI初心者(将来)… {writes}   … 文案は書くが動画は作らない
--     「まとめて仕込む」は writes があるときだけ出し、
--     videos が無ければ動画づくりを飛ばして文だけ予約する。
--
--   SQL Editor に貼って Run するだけ。何度実行しても壊れません。
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. 使う機能
--
--    ★ 既定は空。
--      v3〜v5 では「いま動いているものを壊さない」ために既定値を
--      付け替えたが、ここは事情が違う。いまある運用アカウントは
--      「ひろや｜AI初心者」で、本人の希望は「今までどおり自分で書く」。
--      つまり空が正しい。これから作るものも、必要な機能を選んで入れる。
-- ----------------------------------------------------------------------------
alter table account_groups add column if not exists features text[] not null default '{}';

comment on column account_groups.features is
  '使う機能。writes=文案を自動で書く / videos=動画を自動で作る。無いものは画面に出さない。';

-- 打ち間違いを入れさせない。lib/groups.js の FEATURES と同じ。
alter table account_groups drop constraint if exists account_groups_features_check;
alter table account_groups add constraint account_groups_features_check
  check (features <@ array['writes','videos']);
